namespace Feature.Core.Infrastructure.Interfaces
{
    /// <summary>
    /// Чистое хранилище переиспользуемых объектов.
    /// Пул ничего не создаёт и не вызывает Activate/Deactivate/Show/Hide на объектах -
    /// это ответственность вызывающей стороны (системы).
    /// Если объектов не хватает - вызывающая сторона сама создаёт объект (например через фабрику)
    /// и кладёт его в пул через Prewarm/Return, либо просто использует его напрямую и вернёт позже.
    /// </summary>
    public interface IObjectPool<T>
    {
        /// <summary>Количество свободных объектов, готовых к выдаче.</summary>
        int FreeCount { get; }
 
        /// <summary>
        /// Пытается забрать свободный объект из пула.
        /// Возвращает false, если свободных объектов нет - в этом случае
        /// вызывающая сторона должна создать объект сама (через фабрику) и в дальнейшем
        /// вернуть его в пул через Return, чтобы он переиспользовался.
        /// </summary>
        bool TryGet(out T item);
 
        /// <summary>Возвращает объект обратно в пул как свободный.</summary>
        void Return(T item);
 
        /// <summary>Добавляет заранее созданный объект в пул как свободный (для прогрева).</summary>
        void Prewarm(T item);
    }
}